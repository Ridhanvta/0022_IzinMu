BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_no    VARCHAR(30)  NOT NULL,
    full_name      VARCHAR(150) NOT NULL,
    email          VARCHAR(254) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT users_identity_no_uk UNIQUE (identity_no),
    CONSTRAINT users_identity_no_chk CHECK (length(btrim(identity_no)) > 0),
    CONSTRAINT users_full_name_chk CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT users_email_chk CHECK (
        email = lower(email)
        AND email = btrim(email)
        AND email NOT LIKE '% %'
        AND position('@' IN email) > 1
        AND length(email) <= 254
    ),
    CONSTRAINT users_role_chk CHECK (role IN ('ADMIN', 'STUDENT', 'INSTRUCTOR'))
);

CREATE UNIQUE INDEX users_email_lower_uk ON users (lower(email));
CREATE INDEX users_role_active_idx ON users (role, is_active);
CREATE INDEX users_full_name_trgm_idx ON users USING GIN (full_name gin_trgm_ops);
CREATE INDEX users_identity_no_trgm_idx ON users USING GIN (identity_no gin_trgm_ops);

-- ---------------------------------------------------------------------------
-- courses
-- ---------------------------------------------------------------------------
CREATE TABLE courses (
    course_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code  VARCHAR(20)  NOT NULL,
    course_name  VARCHAR(150) NOT NULL,
    class_day    VARCHAR(10)  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT courses_code_uk UNIQUE (course_code),
    CONSTRAINT courses_code_chk CHECK (
        length(btrim(course_code)) > 0
        AND course_code = upper(course_code)
    ),
    CONSTRAINT courses_name_chk CHECK (length(btrim(course_name)) > 0),
    CONSTRAINT courses_class_day_chk CHECK (
        class_day IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')
    )
);

CREATE INDEX courses_class_day_idx ON courses (class_day);
CREATE INDEX courses_name_trgm_idx ON courses USING GIN (course_name gin_trgm_ops);
CREATE INDEX courses_code_trgm_idx ON courses USING GIN (course_code gin_trgm_ops);

-- ---------------------------------------------------------------------------
-- course_instructors
-- ---------------------------------------------------------------------------
CREATE TABLE course_instructors (
    course_instructor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id            BIGINT      NOT NULL,
    instructor_user_id   BIGINT      NOT NULL,
    assigned_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT course_instructors_course_fk
        FOREIGN KEY (course_id) REFERENCES courses (course_id) ON DELETE RESTRICT,
    CONSTRAINT course_instructors_instructor_fk
        FOREIGN KEY (instructor_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT course_instructors_pair_uk UNIQUE (course_id, instructor_user_id)
);

CREATE INDEX course_instructors_instructor_idx ON course_instructors (instructor_user_id);

-- ---------------------------------------------------------------------------
-- course_enrollments
-- ---------------------------------------------------------------------------
CREATE TABLE course_enrollments (
    enrollment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id        BIGINT      NOT NULL,
    student_user_id  BIGINT      NOT NULL,
    enrolled_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT course_enrollments_course_fk
        FOREIGN KEY (course_id) REFERENCES courses (course_id) ON DELETE RESTRICT,
    CONSTRAINT course_enrollments_student_fk
        FOREIGN KEY (student_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT course_enrollments_pair_uk UNIQUE (course_id, student_user_id)
);

CREATE INDEX course_enrollments_student_idx ON course_enrollments (student_user_id);

-- ---------------------------------------------------------------------------
-- leave_requests
-- ---------------------------------------------------------------------------
CREATE TABLE leave_requests (
    leave_request_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id      BIGINT       NOT NULL,
    course_id            BIGINT       NOT NULL,
    category             VARCHAR(20)  NOT NULL,
    class_date           DATE         NOT NULL,
    evidence_object_key  VARCHAR(1024) NOT NULL,
    status               VARCHAR(20)  NOT NULL DEFAULT 'SUBMITTED',
    instructor_note      TEXT,
    reviewed_by          BIGINT,
    submitted_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    reviewed_at          TIMESTAMPTZ,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT leave_requests_student_fk
        FOREIGN KEY (student_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT leave_requests_course_fk
        FOREIGN KEY (course_id) REFERENCES courses (course_id) ON DELETE RESTRICT,
    CONSTRAINT leave_requests_reviewer_fk
        FOREIGN KEY (reviewed_by) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT leave_requests_category_chk CHECK (
        category IN ('SICK', 'ACADEMIC', 'EMERGENCY', 'FAMILY')
    ),
    CONSTRAINT leave_requests_status_chk CHECK (
        status IN ('SUBMITTED', 'APPROVED', 'REJECTED')
    ),
    CONSTRAINT leave_requests_review_state_chk CHECK (
        (status = 'SUBMITTED' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR
        (status IN ('APPROVED', 'REJECTED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT leave_requests_evidence_key_chk CHECK (
        length(btrim(evidence_object_key)) > 0
        AND lower(evidence_object_key) NOT LIKE 'http%'
    ),
    CONSTRAINT leave_requests_one_per_date_uk UNIQUE (student_user_id, course_id, class_date)
);

CREATE INDEX leave_requests_student_submitted_idx
    ON leave_requests (student_user_id, submitted_at DESC);
CREATE INDEX leave_requests_course_status_idx
    ON leave_requests (course_id, status, submitted_at DESC);
CREATE INDEX leave_requests_status_submitted_idx
    ON leave_requests (status, submitted_at DESC);
CREATE INDEX leave_requests_class_date_idx
    ON leave_requests (class_date);
CREATE INDEX leave_requests_category_date_idx
    ON leave_requests (category, class_date);
CREATE INDEX leave_requests_reviewer_idx
    ON leave_requests (reviewed_by) WHERE reviewed_by IS NOT NULL;

-- ---------------------------------------------------------------------------
-- refresh_tokens
-- ---------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    token_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL,
    token_hash             CHAR(64)     NOT NULL,
    issued_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at             TIMESTAMPTZ  NOT NULL,
    revoked_at             TIMESTAMPTZ,
    replaced_by_token_id   BIGINT,
    user_agent             VARCHAR(255),
    CONSTRAINT refresh_tokens_user_fk
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT refresh_tokens_replacement_fk
        FOREIGN KEY (replaced_by_token_id) REFERENCES refresh_tokens (token_id) ON DELETE SET NULL,
    CONSTRAINT refresh_tokens_hash_uk UNIQUE (token_hash),
    CONSTRAINT refresh_tokens_hash_chk CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT refresh_tokens_expiry_chk CHECK (expires_at > issued_at)
);

CREATE INDEX refresh_tokens_user_expiry_idx
    ON refresh_tokens (user_id, expires_at DESC);
CREATE INDEX refresh_tokens_active_idx
    ON refresh_tokens (expires_at) WHERE revoked_at IS NULL;

COMMIT;
